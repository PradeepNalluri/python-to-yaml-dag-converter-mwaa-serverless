"""Companion Python module that holds the plain functions of TaskFlow tasks.

DagFactory decorator tasks need a plain, importable function as 'python_callable': DagFactory inspects its
arguments and wraps it with the decorator itself. TaskFlow functions are neither plain (module-level names are
@task-decorated objects) nor always importable (functions defined inside the @dag function).

The converter therefore copies the source of the TaskFlow functions defined in the Dag file into a generated
'<dag_id>_taskflow.py' module, together with what they use from the Dag file: its imports, helper functions and
classes, and constants. The module never imports the Dag file itself, which would create the original Dag again
next to the converted one. Functions defined in other modules are imported from there.

    from airflow.providers.amazon.aws.hooks.s3 import S3Hook

    def count_lines(aws_conn_id, bucket, file):
        hook = S3Hook(aws_conn_id=aws_conn_id)
        ...
"""

import ast
import builtins
import dis
import inspect
import re
import sys
import textwrap
from pathlib import Path
from types import CodeType, ModuleType
from typing import Any

from airflow.models.dag import DAG

from dag_converter.conversion.exceptions import InvalidOperatorError
from dag_converter.conversion.tasks import get_python_callable

TASKFLOW_MODULE_SUFFIX = "_taskflow"

_MODULE_HEADER = '''"""Generated by python-to-yaml-dag-converter-mwaa-serverless for Dag '{dag_id}'.

Holds the plain functions of the Dag's TaskFlow tasks for DagFactory decorator tasks.
"""
'''

_UNDECORATED_HELPER = '''def _undecorated(obj):
    """Return the function wrapped by a TaskFlow decorator, or obj when it is not decorated"""
    return getattr(obj, "function", obj)
'''

_CONSTANT_TYPES = (type(None), bool, int, float, complex, str, bytes)


def get_taskflow_module_name(dag_id: str) -> str:
    """Python module name of the companion module for 'dag_id'. Dag ids may contain '-' and '.'"""
    module_name = re.sub(r"\W", "_", dag_id) + TASKFLOW_MODULE_SUFFIX
    if module_name[0].isdigit():
        module_name = f"_{module_name}"
    return module_name


def build_taskflow_module(
    dag_object: DAG, dag_file_path: Path, tasks: dict[str, dict[str, Any]]
) -> tuple[str, str] | None:
    """
    Point the 'python_callable' of every decorator task at the companion module, and build that module.

    Args:
        dag_object: Dag loaded from 'dag_file_path', used to get the TaskFlow functions
        dag_file_path: Python Dag file
        tasks: Converted tasks. Updated in place

    Returns:
        (module name, module source), or None when the Dag has no decorator tasks

    Raises:
        InvalidOperatorError: A TaskFlow function uses something that cannot be copied into the module
    """
    module_name = get_taskflow_module_name(dag_object.dag_id)
    builder = _ModuleBuilder(dag_file_path)

    for task_id, task in tasks.items():
        if "decorator" not in task:
            continue
        python_callable = get_python_callable(dag_object.get_task(task_id))
        if python_callable is None:
            continue
        task["python_callable"] = f"{module_name}.{builder.add_task_function(python_callable)}"

    if not builder.blocks:
        return None
    return module_name, builder.render(dag_object.dag_id)


class _ModuleBuilder:
    def __init__(self, dag_file_path: Path):
        self.dag_file_path = Path(dag_file_path).resolve()
        self.dag_file_imports = _get_top_level_imports(self.dag_file_path)
        self.imports: list[str] = []
        self.blocks: list[str] = []
        self.uses_undecorated = False
        # Module-level name -> the object it holds, to resolve each name once and detect conflicts
        self.names: dict[str, Any] = {}

    def add_task_function(self, python_callable) -> str:
        """Add a TaskFlow function and return its name in the module"""
        function = getattr(python_callable, "function", python_callable)
        for name, value in self.names.items():
            if value is function:
                return name

        if self._is_from_dag_file(function) or "<locals>" in function.__qualname__:
            return self._copy_definition(function, self._unique_name(function.__name__))

        # Functions from other modules are importable, importing them does not create the Dag
        name = self._unique_name(function.__name__)
        self.names[name] = function
        self._add_import(f"import {function.__module__}")
        self.uses_undecorated = True
        self.blocks.append(f"{name} = _undecorated({function.__module__}.{function.__qualname__})")
        return name

    def render(self, dag_id: str) -> str:
        sections = [_MODULE_HEADER.format(dag_id=dag_id)]
        if self.imports:
            sections.append("\n".join(self.imports))
        if self.uses_undecorated:
            sections.append(_UNDECORATED_HELPER)
        sections.extend(self.blocks)
        return "\n\n\n".join(section.strip("\n") for section in sections) + "\n"

    def _is_from_dag_file(self, obj) -> bool:
        try:
            source_file = inspect.getsourcefile(obj)
        except TypeError:
            return False
        return bool(source_file) and Path(source_file).resolve() == self.dag_file_path

    def _unique_name(self, name: str) -> str:
        unique = name
        index = 1
        while unique in self.names:
            unique = f"{name}_{index}"
            index += 1
        return unique

    def _copy_definition(self, obj, name: str) -> str:
        """Copy the source of a function or class without its decorators, after what it uses"""
        self.names[name] = obj
        try:
            source = textwrap.dedent(inspect.getsource(obj))
        except (OSError, TypeError) as e:
            raise InvalidOperatorError(f"Source of {obj.__qualname__} is not available: {e}") from e

        node = ast.parse(source).body[0]
        if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            raise InvalidOperatorError(f"TaskFlow callable {obj.__qualname__} must be defined with 'def'")

        # Decorators come before node.lineno
        definition = "\n".join(source.splitlines()[node.lineno - 1 : node.end_lineno])
        if name != obj.__name__:
            pattern = rf"^((async\s+)?(def|class)\s+){re.escape(obj.__name__)}\b"
            definition = re.sub(pattern, rf"\g<1>{name}", definition)

        for used_name in _get_used_names(obj, node):
            self._resolve(used_name, obj)
        self.blocks.append(definition)
        return name

    def _resolve(self, name: str, user):
        """Make module-level 'name', used by 'user', available in the module"""
        closure = _get_closure_values(user)
        module_globals = _get_globals(user)
        if name in closure:
            value = closure[name]
        elif name in module_globals:
            value = module_globals[name]
        else:
            # Builtins, or local names of class bodies and methods
            return

        if name in self.names:
            if self.names[name] is value or (_is_constant(value) and self.names[name] == value):
                return
            raise InvalidOperatorError(
                f"TaskFlow function {user.__qualname__} uses '{name}', which is bound to different values"
            )

        if name in self.dag_file_imports and name not in closure:
            self.names[name] = value
            self._add_import(self.dag_file_imports[name])
        elif isinstance(value, ModuleType):
            self.names[name] = value
            self._add_import(f"import {value.__name__}" + ("" if value.__name__ == name else f" as {name}"))
        elif (inspect.isfunction(value) or inspect.isclass(value)) and (
            self._is_from_dag_file(value) or "<locals>" in value.__qualname__
        ):
            self._copy_definition(value, name)
        elif inspect.isfunction(value) or inspect.isclass(value):
            self.names[name] = value
            self._add_import(
                f"from {value.__module__} import {value.__qualname__}"
                + ("" if value.__qualname__ == name else f" as {name}")
            )
        elif _is_constant(value):
            self.names[name] = value
            self.blocks.append(f"{name} = {value!r}")
        else:
            raise InvalidOperatorError(
                f"TaskFlow function {user.__qualname__} uses '{name}' ({type(value).__name__}), "
                "which cannot be copied into the TaskFlow module"
            )

    def _add_import(self, statement: str):
        if statement not in self.imports:
            self.imports.append(statement)


def _get_top_level_imports(dag_file_path: Path) -> dict[str, str]:
    """Map each name bound by a top-level import of the Dag file to an import statement for it"""
    tree = ast.parse(dag_file_path.read_text())
    imports = {}
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    imports[alias.asname] = f"import {alias.name} as {alias.asname}"
                else:
                    imports[alias.name.split(".")[0]] = f"import {alias.name}"
        elif isinstance(node, ast.ImportFrom) and node.module != "__future__" and node.level == 0:
            for alias in node.names:
                if alias.name == "*":
                    continue
                statement = f"from {node.module} import {alias.name}"
                imports[alias.asname or alias.name] = statement + (f" as {alias.asname}" if alias.asname else "")
    return imports


def _get_used_names(obj, node: ast.AST) -> list[str]:
    """Names a copied function or class reads from its module or enclosing function"""
    names: list[str] = []
    if inspect.isfunction(obj):
        names.extend(_get_code_names(obj.__code__))
        names.extend(obj.__code__.co_freevars)
    # Default values, annotations and class bodies are evaluated when the definition runs
    if isinstance(node, ast.ClassDef):
        evaluated = node.bases + node.keywords + node.body
    else:
        arguments = node.args
        evaluated = [*arguments.defaults, *[d for d in arguments.kw_defaults if d], node.returns]
        evaluated += [a.annotation for a in arguments.posonlyargs + arguments.args + arguments.kwonlyargs]
        evaluated += [a.annotation for a in (arguments.vararg, arguments.kwarg) if a]
    for expression in evaluated:
        if expression is not None:
            names.extend(n.id for n in ast.walk(expression) if isinstance(n, ast.Name))

    used = []
    for name in names:
        is_builtin = hasattr(builtins, name) and name not in _defined(obj)
        if name not in used and not name.startswith("__") and not is_builtin:
            used.append(name)
    return used


def _defined(obj) -> set[str]:
    """Names that shadow builtins in the function's module or closure"""
    return set(_get_globals(obj)) | set(_get_closure_values(obj))


def _get_globals(obj) -> dict[str, Any]:
    """Module globals of a function or class"""
    if hasattr(obj, "__globals__"):
        return obj.__globals__
    module = sys.modules.get(getattr(obj, "__module__", ""), None)
    return vars(module) if module else {}


def _get_code_names(code: CodeType) -> list[str]:
    """
    Global names read by a code object and the code objects nested in it (comprehensions, lambdas, ...).

    co_names also holds attribute names ('client.create_queue'), so only global loads are used.
    """
    names = [
        instruction.argval
        for instruction in dis.get_instructions(code)
        if instruction.opname in ("LOAD_GLOBAL", "LOAD_NAME")
    ]
    for const in code.co_consts:
        if isinstance(const, CodeType):
            names.extend(_get_code_names(const))
            names.extend(const.co_freevars)
    return names


def _get_closure_values(obj) -> dict[str, Any]:
    closure = getattr(obj, "__closure__", None) or ()
    values = {}
    for name, cell in zip(getattr(getattr(obj, "__code__", None), "co_freevars", ()), closure, strict=False):
        try:
            values[name] = cell.cell_contents
        except ValueError:
            continue
    return values


def _is_constant(value) -> bool:
    """Values whose repr() recreates them"""
    # Exact types: subclasses such as IntEnum do not recreate themselves from repr()
    if type(value) in _CONSTANT_TYPES:
        # nan is not equal to itself and its repr() is not a valid literal
        return not (isinstance(value, float) and value != value)
    if type(value) in (list, tuple, set, frozenset):
        return all(_is_constant(item) for item in value)
    if type(value) is dict:
        return all(_is_constant(k) and _is_constant(v) for k, v in value.items())
    return False
