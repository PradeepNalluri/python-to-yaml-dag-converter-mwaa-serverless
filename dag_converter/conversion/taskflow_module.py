"""Companion Python module that exposes the undecorated functions of TaskFlow tasks.

In a TaskFlow Dag file the module-level names are @task-decorated objects, not functions. DagFactory decorator
tasks need the plain function as 'python_callable' (it inspects its arguments and wraps it with the decorator
itself), so the converter generates a module that unwraps them:

    import simple_taskflow

    double_number = _undecorated(simple_taskflow.double_number)

and points the YAML at it with 'python_callable: <dag_id>_taskflow.double_number'.
"""

import re
from typing import Any

TASKFLOW_MODULE_SUFFIX = "_taskflow"

_MODULE_HEADER = '''"""Generated by python-to-yaml-dag-converter-mwaa-serverless for Dag '{dag_id}'.

Exposes the undecorated functions of the Dag's TaskFlow tasks for DagFactory decorator tasks.
"""

'''

_UNDECORATED_HELPER = '''

def _undecorated(obj):
    """Return the function wrapped by a TaskFlow decorator, or obj when it is not decorated"""
    return getattr(obj, "function", obj)

'''


def get_taskflow_module_name(dag_id: str) -> str:
    """Python module name of the companion module for 'dag_id'. Dag ids may contain '-' and '.'"""
    module_name = re.sub(r"\W", "_", dag_id) + TASKFLOW_MODULE_SUFFIX
    if module_name[0].isdigit():
        module_name = f"_{module_name}"
    return module_name


def build_taskflow_module(dag_id: str, tasks: dict[str, dict[str, Any]]) -> tuple[str, str] | None:
    """
    Point the 'python_callable' of every decorator task at the companion module, and build that module.

    Args:
        dag_id: Id of the converted Dag
        tasks: Converted tasks, with 'python_callable' in '<module>.<function>' format. Updated in place

    Returns:
        (module name, module source), or None when the Dag has no decorator tasks
    """
    module_name = get_taskflow_module_name(dag_id)

    # Map each exposed name to the (source module, attribute) it unwraps
    exposed: dict[str, tuple[str, str]] = {}
    for task in tasks.values():
        if "decorator" not in task or not isinstance(task.get("python_callable"), str):
            continue

        source_module, attribute = task["python_callable"].rsplit(".", 1)
        name = attribute
        # Functions with the same name in different modules get a module-prefixed name
        if exposed.get(name, (source_module, attribute)) != (source_module, attribute):
            name = re.sub(r"\W", "_", source_module) + "__" + attribute
        exposed[name] = (source_module, attribute)
        task["python_callable"] = f"{module_name}.{name}"

    if not exposed:
        return None

    imports = sorted({source_module for source_module, _ in exposed.values()})
    assignments = [
        f"{name} = _undecorated({source_module}.{attribute})" for name, (source_module, attribute) in exposed.items()
    ]
    source = (
        _MODULE_HEADER.format(dag_id=dag_id)
        + "\n".join(f"import {module}" for module in imports)
        + "\n"
        + _UNDECORATED_HELPER
        + "\n"
        + "\n".join(assignments)
        + "\n"
    )
    return module_name, source
