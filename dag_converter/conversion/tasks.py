import importlib
import inspect
from enum import Enum
from pathlib import Path

from airflow.models.dag import DAG
from airflow.models.operator import Operator
from airflow.sdk.bases.decorator import DecoratedOperator
from airflow.sdk.definitions.mappedoperator import MappedOperator
from airflow.utils.types import ArgNotSet

from dag_converter.cleanup import get_cleanup_dag
from dag_converter.conversion.dynamic_mapping import handle_dynamic_task_mapping
from dag_converter.conversion.exceptions import InvalidOperatorError
from dag_converter.conversion.operators.python_decorator import handle_python_decorator
from dag_converter.schema_parser import ArgumentValidator
from dag_converter.taskflow_parser import TaskFlowAnalyzer

# Constructor arguments that describe the Dag structure rather than the task. Dag context managers inject
# these into every operator, and DagFactory rebuilds them from the YAML
STRUCTURAL_TASK_PARAMETERS = {"dag", "task_group"}

# DecoratedOperator internals that the decorator sets itself
DECORATOR_INTERNAL_PARAMETERS = {"kwargs_to_upstream"}


def convert_tasks(
    taskflow_parser: TaskFlowAnalyzer, dag_object: DAG, dag_file_path: Path, validator: ArgumentValidator
):
    """Convert each task into acceptable DagFactory format"""
    tasks = {}
    task_types = {}
    
    # Get DAG-level params to filter them out from tasks
    dag_params_obj = getattr(dag_object, "params", None)
    dag_params = {}
    if dag_params_obj and hasattr(dag_params_obj, "items"):
        for key, param in dag_params_obj.items():
            if hasattr(param, "value"):
                dag_params[key] = param.value
            else:
                dag_params[key] = param

    dag_default_args = getattr(dag_object, "default_args", None) or {}

    # First iteration through tasks to map each task id to its corresponding operator type
    for task in dag_object.tasks:
        task_id = task.task_id
        if not task_id:
            continue

        task_types[task_id] = task.task_type

    operator_task_ids = {task.task_id for task in dag_object.tasks if not is_decorated_task(task)}

    # Second iteration through tasks to handle the actual conversion
    for task in dag_object.tasks:
        task_id = task.task_id
        if not task_id:
            continue

        # Check if params was explicitly set (different from DAG params)
        init_kwargs = getattr(task, "_BaseOperator__init_kwargs", {})
        params_in_init = init_kwargs.get("params", {})
        params_explicitly_set = "params" in init_kwargs and params_in_init != dag_params

        # Edge case for DTM, since it stores the actual operator module in '_task_module' instead
        if isinstance(task, MappedOperator):
            operator_class = task.operator_class
            full_operator_name = f"{task._task_module}.{task.task_type}"
        else:
            operator_class = type(task)
            full_operator_name = f"{task.__module__}.{task.task_type}"

        # TaskFlow tasks (@task, @task.branch, ...) are converted to DagFactory 'decorator' tasks
        decorator_import_path = None
        if is_decorated_task(task):
            decorator_import_path = get_decorator_import_path(operator_class)
            if not decorator_import_path:
                raise InvalidOperatorError(f"Decorator for {task.task_type} is not supported")

        tasks[task_id] = {"operator": full_operator_name}
        valid_task_parameters = get_operator_parameters(full_operator_name)
        if decorator_import_path:
            valid_task_parameters = [p for p in valid_task_parameters if p not in DECORATOR_INTERNAL_PARAMETERS]

        # Only read attributes that map to constructor parameters. Reading every attribute in dir(task)
        # evaluates lazy properties (e.g. SQL operator hooks) that open connections to external systems
        for key in sorted(valid_task_parameters):
            try:
                value = getattr(task, key, None)
            except Exception:
                continue
            # Filter out extraneous task parameters generated by DagBag through validation
            if validator.validate_field("task", key, value):
                # Skip DTM keywords, those will be handled in another function
                # TODO: check if op_kwargs_expand_input exists in Dag Object
                if (
                    key in ["op_kwargs_expand_input", "expand_input", "partial_kwargs", "map_index_template"]
                    or value is None
                    or isinstance(value, ArgNotSet)
                    # Operators may convert defaults into enums in __init__ (e.g. SqlToS3Operator.file_format),
                    # which they do not accept back as input. Unless the user passed them they are only defaults
                    or (isinstance(value, Enum) and not isinstance(value, str) and key not in init_kwargs)
                ):
                    pass
                # Skip params only if they match DAG params AND were not explicitly set
                elif key == "params" and value == dag_params and not params_explicitly_set:
                    pass
                else:
                    tasks[task_id][key] = value

        # These are the core parameters that Python file has for each operator/sensor.
        # Helps find any additional missing parameters (important)
        if hasattr(task, "_BaseOperator__init_kwargs"):
            parameters = getattr(task, "_BaseOperator__init_kwargs", None)
            for key, value in parameters.items():
                if (
                    key not in valid_task_parameters
                    or key in STRUCTURAL_TASK_PARAMETERS
                    or value is None
                    or isinstance(value, ArgNotSet)
                ):
                    continue
                # Parameters explicitly passed by the user are kept even if the schema does not list them,
                # so operators outside the schema keep their operator-specific arguments.
                # Parameters the schema does list must still pass its value checks
                if validator.is_known_field("task", key):
                    if not validator.validate_field("task", key, value):
                        continue
                # Airflow merges Dag default_args into every operator's kwargs. Those are already in the
                # Dag's default_args, so they are only repeated on the task when overridden
                elif key in dag_default_args and value == dag_default_args[key]:
                    continue
                # Skip params only if they match DAG params AND were not explicitly set
                if key == "params" and value == dag_params and not params_explicitly_set:
                    continue
                tasks[task_id][key] = value

        tasks[task_id]["dependencies"] = list(getattr(task, "upstream_task_ids", []))

        # Handle DTM
        if isinstance(task, MappedOperator):
            handle_dynamic_task_mapping(tasks[task_id], task_types, task, validator)

        # Handle operator-specific parameters that we need to delete
        if "operators.appflow" in full_operator_name and "flow_update" in tasks[task_id]:
            del tasks[task_id]["flow_update"]

        if "sensors.eks" in full_operator_name and "target_state_type" in tasks[task_id]:
            del tasks[task_id]["target_state_type"]

        if "sensors.sagemaker" in full_operator_name and "resource_type" in tasks[task_id]:
            del tasks[task_id]["resource_type"]

        filter_config = [
            "SageMakerStartPipelineOperator",
            "SageMakerStopPipelineOperator",
            "SageMakerCreateExperimentOperator",
        ]
        if task.task_type in filter_config and "config" in tasks[task_id]:
            del tasks[task_id]["config"]

        if task.task_type == "MwaaDagRunSensor":
            if "success_states" in tasks[task_id]:
                del tasks[task_id]["success_states"]
            if "failure_states" in tasks[task_id]:
                del tasks[task_id]["failure_states"]

        if decorator_import_path:
            # Convert python callables and XComArgs to strings before restructuring the call arguments
            tasks[task_id] = get_cleanup_dag(tasks[task_id])
            handle_python_decorator(
                tasks[task_id], decorator_import_path, get_callable_parameter_names(task), operator_task_ids
            )

    return tasks


def is_decorated_task(task: Operator) -> bool:
    """Whether the task was created by a TaskFlow decorator"""
    operator_class = task.operator_class if isinstance(task, MappedOperator) else type(task)
    return isinstance(operator_class, type) and issubclass(operator_class, DecoratedOperator)


def get_decorator_import_path(operator_class: type) -> str | None:
    """
    Returns the import path of the decorator that creates 'operator_class'.

    Decorators live in the same module as their operator, e.g. '_BranchPythonDecoratedOperator' and
    'branch_task' (@task.branch) in airflow.providers.standard.decorators.branch_python.
    """
    module = importlib.import_module(operator_class.__module__)
    for name, obj in vars(module).items():
        if (
            inspect.isfunction(obj)
            and obj.__module__ == module.__name__
            and name.endswith("_task")
            and not name.startswith("_")
        ):
            return f"{module.__name__}.{name}"
    return None


def get_python_callable(task: Operator):
    """Returns the python callable of a task. Mapped tasks keep it in 'partial_kwargs'"""
    python_callable = getattr(task, "python_callable", None)
    if python_callable is None and isinstance(task, MappedOperator):
        python_callable = task.partial_kwargs.get("python_callable")
    return python_callable


def get_callable_parameter_names(task: Operator) -> list[str]:
    """Returns the parameter names of a TaskFlow task's python callable, in positional order"""
    python_callable = get_python_callable(task)
    if python_callable is None:
        return []
    return list(inspect.signature(python_callable).parameters)


def get_operator_parameters(operator_class_or_string: type[Operator] | str) -> list[str]:
    """
    Returns a list of all allowed parameters for a given operator.

    Args:
        operator_class_or_string: Either the operator class or a string like
                                 'airflow.providers.amazon.aws.operators.ec2.EC2TerminateInstanceOperator'

    Returns:
        list: List of parameter names that the operator accepts
    """
    # If it's a string, import the class
    if isinstance(operator_class_or_string, str):
        module_path, class_name = operator_class_or_string.rsplit(".", 1)
        try:
            module = importlib.import_module(module_path)
            operator_class = getattr(module, class_name)
        except (ImportError, AttributeError):
            return []
    else:
        operator_class = operator_class_or_string

    all_params = []

    for cls in operator_class.__mro__:
        if hasattr(cls, "__init__"):
            try:
                sig = inspect.signature(cls.__init__)
                params = [name for name in sig.parameters if name not in ["self", "args", "kwargs"]]
                all_params.extend(params)
            except Exception:
                continue

    # Remove duplicates while preserving order
    return list(dict.fromkeys(all_params))
